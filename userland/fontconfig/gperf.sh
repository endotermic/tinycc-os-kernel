#!/bin/sh
# SPDX-License-Identifier: BSD-2-Clause
# gperf.sh - a stand-in for GNU gperf, for fontconfig's object-name table.  fontconfig
# generates src/fcobjshash.h at build time with gperf, which this host does not have (and
# which the release tarball does not ship pre-generated).  gperf would emit a perfect hash
# over the ~60 property names ("family", "weight", ...); this emits a table and a linear
# search with the same interface, which the few lookups fontconfig makes at pattern build
# time do not notice.  scripts/build.sh passes it as GPERF= to fontconfig's make.
# Usage: userland/fontconfig/gperf.sh [gperf options] fcobjshash.gperf > fcobjshash.h
#   Input: a gperf file after fontconfig's cpp pass: a declarations section (%{ ... %} and
#   %-directives, with "struct FcObjectTypeInfo { int name; int id; };"), a %% line, then
#   one keyword per line: "name",ID (the ID a C expression), and an optional final %%.
#   The functions the input's directives name (hash-function-name, lookup-function-name)
#   are defined; the struct's first field, gperf's string-pool offset, stays 0.
set -e
case ${1:-} in -h|--help) sed -n '3,/^[^#]/p' "$0" | sed '$d' | cut -c3-; exit 0;; esac
in=
for a; do case $a in -*) ;; *) in=$a;; esac; done
[ -n "$in" ] && [ -f "$in" ] || { echo "gperf.sh: no input file (see --help)" >&2; exit 1; }
awk '
    BEGIN { sect = 0; hash = "hash"; lookup = "in_word_set"; n = 0 }
    sect == 0 && /^%\{/ { verbatim = 1; next }
    sect == 0 && /^%\}/ { verbatim = 0; next }
    sect == 0 && verbatim { print; next }
    sect == 0 && /^%%/ { sect = 1; next }
    sect == 0 && /^%define hash-function-name / { hash = $3; next }
    sect == 0 && /^%define lookup-function-name / { lookup = $3; next }
    sect == 0 && /^%/ { next }
    sect == 0 { print; next }            # the declarations section: the struct, verbatim
    sect == 1 && /^%%/ { sect = 2; next }
    sect == 1 && /^"/ {
        # "name",ID  (fontconfig'\''s Makefile has already removed the blanks around the comma)
        c = index($0, ","); name[n] = substr($0, 1, c - 1); id[n] = substr($0, c + 1); n++; next }
    sect == 1 && /^[^ \t]/ { print "gperf.sh: unexpected keyword line: " $0 > "/dev/stderr"; exit 1 }
    END {
        if (sect == 0) { print "gperf.sh: no %% separator in the input" > "/dev/stderr"; exit 1 }
        print "/* generated by userland/fontconfig/gperf.sh (a linear search in place of gperf'\''s perfect hash) */"
        print "#include <string.h>"
        print "static const struct { const char *str; struct FcObjectTypeInfo info; } FcObjectTypeTable[] = {"
        for (i = 0; i < n; i++) printf("    { %s, { 0, %s } },\n", name[i], id[i])
        print "};"
        print "#define FC_OBJECT_TYPE_COUNT (sizeof FcObjectTypeTable / sizeof FcObjectTypeTable[0])"
        printf("static unsigned int\n%s (register const char *str, register FC_GPERF_SIZE_T len)\n", hash)
        print "{\n    unsigned int i;\n    for (i = 0; i < FC_OBJECT_TYPE_COUNT; i++)"
        print "        if (strlen (FcObjectTypeTable[i].str) == len && memcmp (FcObjectTypeTable[i].str, str, len) == 0)"
        print "            return i;\n    return FC_OBJECT_TYPE_COUNT;\n}"
        printf("static const struct FcObjectTypeInfo *\n%s (register const char *str, register FC_GPERF_SIZE_T len)\n", lookup)
        printf("{\n    unsigned int i = %s (str, len);\n", hash)
        print "    return i < FC_OBJECT_TYPE_COUNT ? &FcObjectTypeTable[i].info : (const struct FcObjectTypeInfo *) 0;\n}"
    }' "$in"
