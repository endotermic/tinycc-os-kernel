        -I. -I"$XP/include" -I"$XP/include/freetype2" \
        -o xfiles xfiles.c widget.c util.c icons.c control/dragndrop.c control/selection.c control/font.c \
        -L"$XP/lib" $XLIBS_XFILES >>"$LOGS/xfiles.log" 2>&1 \
