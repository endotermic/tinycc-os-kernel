# xlib_build NAME [configure options]: one autotools library of the X stack, configured out
# of tree in build/<arch>/x/NAME (static only, --host names the target so that nothing is
# probed by running it; CC and CFLAGS in the environment, as the other steps do), built and
# installed into $XP.  pkg-config is scripts/pkg-config.sh on $XP (x_env).
#
# Each library is a step of its own too (xlib-NAME, the options are in xlib below), so that
# the parallel graph (scripts/parallel.sh) builds them side by side as their dependencies
# allow: configure, which runs one process at a time, is most of their time.  The libraries
# install into the one $XP, each its own files.  A built library leaves $XB/NAME/.installed.
xlib_build() {
    name=$1; shift
    need_src "$name"
    [ -x "$MUSL_TCC" ] || die "no $MUSL_TCC: run the musl step first"
    x_env
    d=$XB/$name; mkdir -p "$d" "$XP/lib/pkgconfig"; cd "$d"; rm -f .installed
    msg "$name: $(lock_ref "$name"), static, musl, CC=musl-tcc -> $XP"
    # pthread-stubs: libxcb and libX11 require the pkg-config module; musl has every pthread
    # function in libc, so the module is empty
    [ "$name" != libxcb ] || cat > "$XP/lib/pkgconfig/pthread-stubs.pc" <<EOF
Name: pthread stubs
Description: Stubs missing from libc for standard pthread functions (none with musl)
Version: 0.5
Libs:
Cflags:
EOF
    # the site cache (xsite_write): libXau's configure keeps its cache (-C) and writes it;
    # every library after libXau reads it (the graph makes them wait for libXau)
    cache=; site=/dev/null
    case $name in
        xorgproto|xtrans) ;;
        libXau) cache=-C;;
        *) [ ! -f "$XSITE" ] || site=$XSITE;;
    esac
    configured config.status "$MUSL_TCC" "--prefix=$XP" \
        || CONFIG_SITE=$site CC=$MUSL_TCC CFLAGS=-O2 CPPFLAGS="-I$XP/include" LDFLAGS="-L$XP/lib" CC_FOR_BUILD=gcc PYTHON=python3 \
            "$SRC/$name/configure" $cache --host="$ARCH-linux-musl" --prefix="$XP" \
            --disable-shared --enable-static --disable-dependency-tracking "$@" >"$LOGS/$name-configure.log" 2>&1 \
        || fail "$LOGS/$name-configure.log" "$name configure failed"
    [ -z "$cache" ] || [ ! -f config.cache ] || xsite_write config.cache
    : >"$LOGS/$name.log"
    run_progress "$name" "$(make_total)" "$LOGS/$name.log" jmake || fail "$LOGS/$name.log" "$name build failed"
    make install >>"$LOGS/$name.log" 2>&1 || fail "$LOGS/$name.log" "$name install failed"
    : > .installed
}

# The site cache $XSITE (CONFIG_SITE for the X libraries, fontconfig, xdm and xedit): the
# answers of libXau's configure that are facts of the toolchain alone, so that the ~35
# configure scripts after it do not each probe them again (a configure takes 20-30% less):
# X.Org's compiler-flag tests (xorg_cv_*), libtool's toolchain checks (lt_cv_*, without its
# global_symbol_* sed programs, which differ between libtool versions, and without where it
# found nm and ld: libXau's libtool records "no" for nm, which xdm's newer one takes as no nm), automake's and the C
# compiler's (am_cv_*, ac_cv_c_*, ac_cv_prog_cc_*, the object and program suffixes, sed and
# grep), musl's headers that exist (ac_cv_header_*=yes for files in $MUSLP/include: a
# header found elsewhere, in $XP, the kernel's, or one not there, is probed as before) and
# musl's functions that exist (ac_cv_func_*=yes for symbols libc.a defines).  It is written
# anew from each build's own libXau configure, so it follows the compiler and musl.
XSITE=$XB/config.site
xsite_write() {
    hdrs=$(cd "$MUSLP/include" && find . -type f | sed 's|^\./||; s/[^A-Za-z0-9]/_/g')
    funcs=$(nm -g --defined-only "$MUSLP/lib/libc.a" 2>/dev/null | awk 'NF == 3 { print $3 }' | sort -u)
    { echo "# generated by scripts/build.sh (xsite_write) from $XB/libXau/config.cache"
      { echo "$hdrs" | sed 's/^/H /'; echo "$funcs" | sed 's/^/F /'; cat "$1"; } | awk '
        $1 == "H" && NF == 2 { h[$2]; next }
        $1 == "F" && NF == 2 { f[$2]; next }
        !/^[A-Za-z_][A-Za-z0-9_]*=\$\{[A-Za-z_][A-Za-z0-9_]*=.*\}$/ { next }   # one-line entries only
        { v = $0; sub(/=.*/, "", v) }
        v ~ /^lt_cv_(sys_global_symbol_|path_|nm_|prog_gnu_ld|ld_)/ { next }   # (the tools: libXau finds no $host-nm, which newer libtools take as no nm at all)
        v ~ /^(xorg_cv_|lt_cv_|am_cv_|ac_cv_c_|ac_cv_prog_cc_)/ || v ~ /^ac_cv_(objext|exeext|path_SED|path_GREP|path_EGREP|path_FGREP)$/ { print; next }
        v ~ /^ac_cv_header_/ { n = substr(v, 15); if ((n in h) && $0 ~ /=yes\}$/) print; next }
        v ~ /^ac_cv_func_/ { n = substr(v, 12); if ((n in f) && $0 ~ /=yes\}$/) print; next }'
    } > "$XSITE.new" && mv "$XSITE.new" "$XSITE"
    echo "   site cache: $(grep -c '^[a-z]' "$XSITE") answers -> $XSITE"
}

# xlib NAME: the X library NAME with its configure options (one table for the groups below
# and for the xlib-NAME steps).  Inside the parallel graph (XLIB_GRAPH=1) the groups only
# check that the library's own step has built it.
XLIB_NAMES="xorgproto xtrans libXau xcb-proto libxcb libX11 libXdmcp libfontenc libXfont libICE libSM libXext libXt libXmu libXpm libXaw libXrender expat freetype fontconfig libXft libXinerama jpeg libXfixes libXcursor xprop xrdb libXcomposite libXdamage xcompmgr"
xlib() {
    if [ -n "${XLIB_GRAPH:-}" ]; then
        [ -f "$XB/$1/.installed" ] || die "$1 is not built: the parallel graph's step xlib-$1 builds it"
        return 0
    fi
    xlib_one "$1"
}
xlib_one() {
    case $1 in
        xorgproto|xtrans|libXau|xcb-proto|libXdmcp|libfontenc|libICE|libXext|libXmu|libXrender|libXft|libXinerama|jpeg|libXfixes|xprop|libXcomposite|libXdamage)
            xlib_build "$1";;
        libxcb) xlib_build libxcb --disable-devel-docs;;
        libX11) xlib_build libX11 --disable-specs --without-xmlto --without-fop --without-xsltproc \
                    --disable-malloc0returnsnull --disable-loadable-i18n;;
        libXfont) xlib_build libXfont --disable-freetype --disable-fc --disable-devel-docs --without-bzip2;;
        libSM) xlib_build libSM --without-libuuid;;
        libXt) xlib_build libXt --disable-xkb --with-appdefaultdir=/usr/share/X11/app-defaults \
                   --with-xfile-search-path='/etc/X11/%L/%T/%N%C%S:/etc/X11/%l/%T/%N%C%S:/etc/X11/%T/%N%C%S:/etc/X11/%L/%T/%N%S:/etc/X11/%l/%T/%N%S:/etc/X11/%T/%N%S:/usr/share/X11/%L/%T/%N%C%S:/usr/share/X11/%l/%T/%N%C%S:/usr/share/X11/%T/%N%C%S:/usr/share/X11/%L/%T/%N%S:/usr/share/X11/%l/%T/%N%S:/usr/share/X11/%T/%N%S';;
        # (libXpm: without gettext, which musl's libc would satisfy and whose message catalogs
        # then want xgettext on the host; the configure cache variable is the only switch)
        libXpm) ac_cv_search_gettext=no xlib_build libXpm --disable-open-zfile --disable-stat-zfile;;
        libXaw) xlib_build libXaw --disable-xaw6;;
        expat) xlib_build expat --without-xmlwf --without-examples --without-tests --without-docbook;;
        freetype) xlib_build freetype --with-zlib=yes --with-png=yes --with-harfbuzz=no --with-brotli=no --with-bzip2=no \
                      --with-librsvg=no --disable-freetype-config;;
        fontconfig) fontconfig_build;;
        libXcursor) xlib_build libXcursor --with-icondir=/usr/share/icons --with-cursorpath='~/.icons:/usr/share/icons:/usr/share/pixmaps';;
        xrdb) xlib_build xrdb --with-cpp=/usr/bin/cpp;;
        # its link line puts -lX11 before the libraries that need it, which a static link
        # cannot resolve: LIBS (appended last) repeats the X11 stack
        xcompmgr) xlib_build xcompmgr LIBS="-lX11 -lxcb -lXau";;
        *) die "unknown X library '$1' (one of: $XLIB_NAMES)";;
    esac
}
step_xlib() { xlib_one "$1"; }

step_xlibs() {
    [ -x "$MUSL_TCC" ] || die "no $MUSL_TCC: run the musl step first"
    need_reset; need_tool python3 cpp; need_done
    # the X client stack that links' X driver needs, all static in $XP: the protocol
    # headers (xorgproto), xtrans (headers: the transport code that libX11 and the server
    # compile in), libXau, xcb-proto (the protocol as XML plus its python generator, which the
    # host's python3 runs when libxcb is built: the only generated C in the stack), libxcb and
    # libX11 (its makekeys runs on the host: CC_FOR_BUILD=gcc; cpp preprocesses the keysym
    # and compose tables)
    for l in xorgproto xtrans libXau xcb-proto libxcb libX11; do xlib "$l"; done
    echo "   $(ls "$XP/lib"/*.a | xargs -n1 basename | tr '\n' ' ')"
}

