    for f in wpa_supplicant wpa_cli wpa_passphrase; do cp "$W/wpa_supplicant/wpa_supplicant/$f" "$STAGE/usr/sbin/"; done
    for f in hostapd hostapd_cli; do cp "$W/hostapd/hostapd/$f" "$STAGE/usr/sbin/"; done
