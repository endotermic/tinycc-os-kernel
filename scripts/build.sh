# xft_stack: the Xft font stack, static in $XP: anti-aliased text through FreeType and
# fontconfig for xdm's greeter and xdm-help (step xdm, which runs first) and for JWM, mlterm,
# xfiles, xmenu and dmenu (a library configured before is not configured again; inside the
# parallel graph each is its own step, built once).
xft_stack() {
    need_src libXrender expat freetype fontconfig libXft
    # libXrender (XRender), expat (fontconfig's XML parser; no xmlwf, examples, tests or
    # docs), FreeType (zlib and libpng from $XP; no bzip2, Brotli, HarfBuzz, librsvg),
    # fontconfig (fontconfig_build) and libXft
    for l in libXrender expat freetype fontconfig libXft; do xlib "$l"; done
}
# fontconfig: its paths are the guest's (the configuration in /etc/fonts, the templates
# in /usr/share/fontconfig/conf.avail, the fonts in /usr/share/fonts, the cache in
# /var/cache/fontconfig), so it is installed under a DESTDIR ($FCD): the library, headers and
# .pc go to $XP, the configuration to the staging tree (step_jwm stages it from $FCD).  No
# gettext, no documentation, no iconv, expat rather than libxml2, and no fc-cache run at
# install time (the cache is built in the guest at first use).  gperf, which generates its
# object-name hash at build time and which this host does not have, is replaced by
# userland/fontconfig/gperf.sh (a linear search with gperf's interface; GPERF= on make's
# command line overrides the "missing gperf" the configure recorded).
FC=$XB/fontconfig; FCD=$FC/dest
fontconfig_build() {
    need_src fontconfig
    [ -x "$MUSL_TCC" ] || die "no $MUSL_TCC: run the musl step first"
    x_env
    mkdir -p "$FC"; cd "$FC"; rm -f .installed
    msg "fontconfig: $(lock_ref fontconfig), static, musl, CC=musl-tcc, expat, gperf stand-in -> $XP, configuration for /etc/fonts"
    site=/dev/null; [ ! -f "$XSITE" ] || site=$XSITE
    configured config.status "$MUSL_TCC" "--prefix=$XP" \
        || CONFIG_SITE=$site CC=$MUSL_TCC CFLAGS=-O2 CPPFLAGS="-I$XP/include" LDFLAGS="-L$XP/lib" CC_FOR_BUILD=gcc PYTHON=python3 \
            "$SRC/fontconfig/configure" --host="$ARCH-linux-musl" --prefix="$XP" --disable-shared --enable-static \
            --disable-dependency-tracking --disable-nls --disable-docs --disable-docbook --disable-cache-build \
            --disable-iconv --disable-libxml2 --with-expat="$XP" \
            --with-default-fonts=/usr/share/fonts --with-add-fonts=no --with-cache-dir=/var/cache/fontconfig \
            --with-baseconfigdir=/etc/fonts --with-configdir=/etc/fonts/conf.d \
            --with-templatedir=/usr/share/fontconfig/conf.avail --with-xmldir=/usr/share/xml/fontconfig \
            >"$LOGS/fontconfig-configure.log" 2>&1 \
        || fail "$LOGS/fontconfig-configure.log" "fontconfig configure failed"
    : >"$LOGS/fontconfig.log"
    set -- GPERF="$ROOT/userland/fontconfig/gperf.sh"
    run_progress "fontconfig" "$(make_total "$@")" "$LOGS/fontconfig.log" jmake "$@" || fail "$LOGS/fontconfig.log" "fontconfig build failed"
    rm -rf "$FCD"
    make "$@" install DESTDIR="$FCD" >>"$LOGS/fontconfig.log" 2>&1 || fail "$LOGS/fontconfig.log" "fontconfig install failed"
    [ -f "$FCD$XP/lib/libfontconfig.a" ] && [ -f "$FCD/etc/fonts/fonts.conf" ] || fail "$LOGS/fontconfig.log" "fontconfig installed neither libfontconfig.a nor fonts.conf"
    cp -a "$FCD$XP/." "$XP/"
    : > .installed
}

step_xdm() {
    need_src xdm
    [ -x "$MUSL_TCC" ] || die "no $MUSL_TCC: run the musl step first"
    [ -f "$XP/lib/libX11.a" ] || die "no libX11.a in $XP: run the xlibs step first"
    x_env
    # the toolkit of xdm's greeter: libICE and libSM (libXt wants them; no libuuid, libSM makes
    # its own client IDs), libXext, libXt (app-defaults and the file search path under
    # /etc/X11 and /usr/share/X11 of the guest, not the build tree; no XKB: TinyX has none),
    # libXmu, libXpm (xdm's configure wants it even with the pixmap logos off) and libXaw
    # (Xaw7 only).  All plain C autotools, static, built as the X client libraries were.
    for l in libICE libSM libXext libXt libXmu libXpm libXaw; do xlib "$l"; done
    # the greeter and xdm-help draw their text with Xft (DejaVu Sans through fontconfig,
    # anti-aliased on the frosted background): the font stack JWM uses too, built here first
    xft_stack
    XD=$XB/xdm; STAGE=$B/xdm/stage; mkdir -p "$XD" "$B/xdm"
    msg "xdm: $(lock_ref xdm), static, musl, CC=musl-tcc, the greeter linked in, Xft -> $STAGE/usr/bin/xdm"
    # a tree configured without Xft (before 2026-11-13) is configured and built again: the
    # greeter's objects depend on config.h's USE_XFT, and there is no dependency tracking
    if [ -f "$XD/config.status" ] && ! grep -q -- '--with-xft' "$XD/config.status"; then
        rm -rf "$XD"; mkdir -p "$XD"
    fi
    cd "$XD"
    # xdm itself: no PAM (the greeter checks /etc/shadow with crypt()), no XDMCP's
    # XDM-AUTHORIZATION-1, no Xinerama, Xft text, no pixmap logos, no xdmshell; its files
    # under /etc/X11/xdm, logs and pid in /tmp, the servers' cookies in /var/run/xdm, the
    # random bytes of the cookies from /dev/urandom.  The greeter is a module that xdm
    # dlopens, which a static musl program cannot: patches/xdm links it in
    # (GREET_USER_STATIC), and the xdm binary is linked here from the objects make built,
    # with the greeter's archive and the toolkit libraries, since the Makefile does not
    # know the greeter as a dependency of the program.
    site=/dev/null; [ ! -f "$XSITE" ] || site=$XSITE
    configured config.status "$MUSL_TCC" "--prefix=$XP" \
        || CONFIG_SITE=$site CC=$MUSL_TCC CFLAGS="-O2 -DGREET_USER_STATIC" CPPFLAGS="-I$XP/include" LDFLAGS="-L$XP/lib" \
            "$SRC/xdm/configure" --host="$ARCH-linux-musl" --prefix="$XP" --disable-shared --enable-static \
            --disable-dependency-tracking --without-pam --without-xinerama --with-xft --disable-xpm-logos \
            --disable-xdm-auth --disable-xdmshell --with-random-device=/dev/urandom \
            --with-xdmconfigdir=/etc/X11/xdm --with-xdmscriptdir=/etc/X11/xdm --with-xdmlibdir=/usr/lib/X11/xdm \
            --with-logdir=/tmp --with-piddir=/tmp --with-authdir=/var/run/xdm --with-default-vt=vt5 \
            --with-default-session=/etc/X11/xdm/Xsession --with-appdefaultdir=/usr/share/X11/app-defaults \
            --without-xmlto --without-fop >"$LOGS/xdm-configure.log" 2>&1 \
        || fail "$LOGS/xdm-configure.log" "xdm configure failed"
    : >"$LOGS/xdm.log"
    # make -k: the Makefile's own link of xdm fails (libtool passes --export-dynamic, for the
    # dlopen that the patch removes, and tcc rejects it); everything else, the greeter's
    # archive included, is built, and the program is linked below from the objects
    run_progress "xdm" "$(make_total)" "$LOGS/xdm.log" jmake -k || true
    greet=$(ls greeter/.libs/libXdmGreet.a greeter/libXdmGreet.a 2>/dev/null | head -1)
    [ -n "$greet" ] || fail "$LOGS/xdm.log" "no libXdmGreet.a (the greeter) in $XD/greeter"
    objs=$(ls xdm/*.o 2>/dev/null)
    [ -n "$objs" ] || fail "$LOGS/xdm.log" "no xdm objects in $XD/xdm"
    "$MUSL_TCC" -O2 -o "$XD/xdm-static" $objs "$greet" \
        $("$PKG_CONFIG" --libs xaw7 xmu xt sm ice xft xrender xext xdmcp x11) -lSM -lICE -lXrender -lXext -lm -lX11 -lxcb -lXau \
        >>"$LOGS/xdm.log" 2>&1 || fail "$LOGS/xdm.log" "xdm link (with the greeter) failed"
    grep -q '^#define USE_XFT 1' config.h || fail "$LOGS/xdm-configure.log" "xdm configured without Xft"
    # the helper text window of the greeter (userland/xdm/xdm-help.c, Xlib + Xft, static)
    "$MUSL_TCC" -O2 -I"$XP/include" -I"$XP/include/freetype2" -o "$XD/xdm-help" "$ROOT/userland/xdm/xdm-help.c" \
        $("$PKG_CONFIG" --libs xft xrender x11) -lXrender -lm -lX11 -lxcb -lXau >>"$LOGS/xdm.log" 2>&1 || fail "$LOGS/xdm.log" "xdm-help build failed"
    # the staging tree appended to the images (stage_lists): xdm and the helper, xdm's
    # configuration and its C scripts under /etc/X11/xdm, the greeter's resources as the
    # Xlogin app-defaults file (xdm would load Xresources through xrdb, which the image has not)
    rm -rf "$STAGE"; mkdir -p "$STAGE/usr/bin" "$STAGE/etc/X11/xdm" "$STAGE/usr/share/X11/app-defaults"
    cp "$XD/xdm-static" "$STAGE/usr/bin/xdm"; cp "$XD/xdm-help" "$STAGE/usr/bin/xdm-help"
    cp "$ROOT/userland/xdm/xdm-config" "$ROOT/userland/xdm/Xservers" "$STAGE/etc/X11/xdm/"
    cp "$ROOT/userland/xdm/Xresources" "$STAGE/usr/share/X11/app-defaults/Xlogin"
    for c in Xsession Xsetup_0 Xstartup; do cp "$ROOT/userland/xdm/$c.c" "$STAGE/etc/X11/xdm/$c"; chmod 755 "$STAGE/etc/X11/xdm/$c"; done
    echo "   xdm: $(file -b "$STAGE/usr/bin/xdm" | cut -d, -f1-2), $(ls -l "$STAGE/usr/bin/xdm" | awk '{print $5}') bytes; xdm-help $(ls -l "$XD/xdm-help" | awk '{print $5}') bytes; /etc/X11/xdm: $(ls "$STAGE/etc/X11/xdm" | tr '\n' ' ')"
}

step_jwm() {
    need_src libXinerama jpeg dejavu-fonts jwm
    [ -x "$MUSL_TCC" ] || die "no $MUSL_TCC: run the musl step first"
    [ -f "$XP/lib/libX11.a" ] && [ -f "$XP/lib/libpng16.a" ] || die "no libX11.a or libpng16.a in $XP: run the zlib, libpng and xlibs steps first"
    [ -f "$XP/lib/libXpm.a" ] && [ -f "$XP/lib/libXmu.a" ] && [ -f "$XP/lib/libXext.a" ] || die "no libXpm.a, libXmu.a or libXext.a in $XP: run the xdm step first"
    x_env
    # Everything JWM can optionally use, static in $XP like the X client libraries (the
    # SVG path, librsvg + cairo, is out of reach: librsvg is Rust since 2.41 and its last C
    # release wants glib, pango and gdk-pixbuf; pango wants glib and harfbuzz, built with
    # meson and C++.  Everything else is plain C autotools): the Xft font stack (xft_stack,
    # already built by the xdm step for its greeter), libXinerama, and IJG's libjpeg
    # (jpeg-9f; its cjpeg/djpeg land in $XP/bin and are not shipped).
    xft_stack
    for l in libXinerama jpeg; do xlib "$l"; done
    JW=$XB/jwm; STAGE=$B/jwm/stage; mkdir -p "$B/jwm"
    msg "jwm: $(lock_ref jwm), static, musl, CC=musl-tcc, Xft + XRender + Xinerama + PNG/JPEG/XPM/XBM icons -> $STAGE/usr/bin/jwm"
    # JWM builds in its source tree only (its sources include ../config.h): a copy of the
    # tree under build/.  Its configure takes pkg-config from PKGCONFIG (scripts/pkg-config.sh
    # here, so the Xft flags carry FreeType's include directory), everything else from the
    # -I/-L flags and the library probes; LIBS carries the whole static closure, so that the
    # probes link under tcc's single-pass linker whatever order configure tries.  No NLS
    # (gettext), no cairo/rsvg (SVG), no pango.  The link itself is done here, not by its
    # Makefile, which puts -lX11 first and the libraries that need it after.
    XLIBS="$("$PKG_CONFIG" --libs xft xinerama xpm xmu xext x11) -ljpeg -lpng16 -lz -lm -lX11 -lxcb -lXau"
    rsync -a --delete --exclude .git "$SRC/jwm/" "$JW/"
    cd "$JW"
    CC=$MUSL_TCC CFLAGS=-O2 CPPFLAGS="-I$XP/include" LDFLAGS="-L$XP/lib" LIBS="$XLIBS" PKGCONFIG=$PKG_CONFIG \
        ./configure --prefix=/usr --sysconfdir=/etc --x-includes="$XP/include" --x-libraries="$XP/lib" \
        --disable-nls --disable-cairo --disable-rsvg --disable-pango >"$LOGS/jwm-configure.log" 2>&1 \
        || fail "$LOGS/jwm-configure.log" "jwm configure failed"
    for f in "PNG:      yes" "JPEG:     yes" "XPM:      yes" "XBM:      yes" "XFT:      yes" "XRender:  yes" "Shape:    yes" "Xmu:      yes" "Xinerama: yes"; do
        grep -q "^    $f" "$LOGS/jwm-configure.log" || fail "$LOGS/jwm-configure.log" "jwm configured without ${f%%:*}"
    done
    : >"$LOGS/jwm.log"
    run_progress "jwm" "$(make_total -C src)" "$LOGS/jwm.log" jmake -C src LDFLAGS="-L$XP/lib $XLIBS" \
        || fail "$LOGS/jwm.log" "jwm build failed"
    [ -x src/jwm ] || fail "$LOGS/jwm.log" "no jwm binary"
    # the staging tree appended to the images (stage_lists): jwm, its system configuration
    # with the menu's icons (userland/jwm/), fontconfig's configuration and templates,
    # fc-list and fc-match (what fontconfig sees, for debugging), and three DejaVu faces
    # (Sans, Sans Bold, Sans Mono; Bitstream Vera license, the file next to them) as the
    # fonts Xft draws with
    rm -rf "$STAGE"; mkdir -p "$STAGE/usr/bin" "$STAGE/etc" "$STAGE/usr/share/jwm" "$STAGE/usr/share/fonts/TTF"
    cp src/jwm "$STAGE/usr/bin/jwm"
    cp "$ROOT/userland/jwm/system.jwmrc" "$STAGE/etc/system.jwmrc"
    cp "$ROOT"/userland/jwm/icons/*.xpm "$STAGE/usr/share/jwm/"
    cp -a "$FCD/etc/fonts" "$STAGE/etc/fonts"
    mkdir -p "$STAGE/usr/share"; cp -a "$FCD/usr/share/fontconfig" "$STAGE/usr/share/fontconfig"
    [ ! -d "$FCD/usr/share/xml" ] || cp -a "$FCD/usr/share/xml" "$STAGE/usr/share/xml"
    rm -f "$STAGE"/etc/fonts/conf.d/README
    cp "$FCD$XP/bin/fc-list" "$FCD$XP/bin/fc-match" "$STAGE/usr/bin/"
    for f in DejaVuSans.ttf DejaVuSans-Bold.ttf DejaVuSansMono.ttf; do cp "$SRC/dejavu-fonts/ttf/$f" "$STAGE/usr/share/fonts/TTF/"; done
    cp "$SRC/dejavu-fonts/LICENSE" "$STAGE/usr/share/fonts/TTF/LICENSE.DejaVu"
    echo "   jwm: $(file -b src/jwm | cut -d, -f1-2), $(ls -l src/jwm | awk '{print $5}') bytes; fc-list $(ls -l "$STAGE/usr/bin/fc-list" | awk '{print $5}') bytes; fonts: $(ls "$STAGE/usr/share/fonts/TTF" | grep -c ttf) DejaVu faces; /etc/fonts/conf.d: $(ls "$STAGE/etc/fonts/conf.d" | wc -l) files"
}
step_mlterm() {
    need_src mlterm
    need_khdr
    [ -x "$MUSL_TCC" ] || die "no $MUSL_TCC: run the musl step first"
    [ -f "$XP/lib/libX11.a" ] || die "no libX11.a in $XP: run the xlibs step first"
    [ -f "$XP/lib/libXft.a" ] && [ -f "$XP/lib/libfontconfig.a" ] || die "no libXft.a or libfontconfig.a in $XP: run the jwm step first"
    x_env
    ML=$B/mlterm; STAGE=$ML/stage; mkdir -p "$ML"
    msg "mlterm: $(lock_ref mlterm), static, musl, CC=musl-tcc, Xlib + Xft (DejaVu Sans Mono through fontconfig) -> $STAGE/usr/bin/mlterm"
    cd "$ML"
    # The terminal emulator of the graphical mode.  mlterm loads its type engines (xcore,
    # xft), character tables, scrollbars and input methods as plugins by default; a static
    # musl program cannot dlopen, so every one it keeps is linked in: --disable-shared makes
    # configure drop the plugin scrollbars (the built-in "simple" stays) and the kbd input
    # method, --disable-dl-type/-table/-ctl link the type engines and libmef's tables in.
    # Type engines xcore (the server's built-in fixed font) and xft (DejaVu Sans Mono through
    # fontconfig: /etc/mlterm/aafont, userland/mlterm/); no cairo, BiDi (fribidi), Indic,
    # OpenType layout (harfbuzz), images (mlimgloader wants gdk-pixbuf), ssh (libssh2),
    # braille, utmp (musl has no utmp) or input method libraries; of the tools mlclient only
    # (opens a window or a pty in a running mlterm; mlconfig and mlterm-menu are GTK).
    # Out-of-tree build (its Makefiles set VPATH).  The Xft closure in LIBS, so that the
    # probes link under tcc's single-pass linker; the program's own link line takes the
    # libraries from pkg-config (scripts/pkg-config.sh: the static closure in order) and
    # from configure's X checks.
    XLIBS="$("$PKG_CONFIG" --libs xft x11) -lm"
    configured config.status "$MUSL_TCC" "--x-libraries=$XP/lib" \
        || CC=$MUSL_TCC CFLAGS=-O2 CPPFLAGS="-I$XP/include" LDFLAGS="-L$XP/lib" LIBS="$XLIBS" \
            "$SRC/mlterm/configure" --host="$ARCH-linux-musl" --prefix=/usr --sysconfdir=/etc \
            --disable-shared --enable-static --with-gui=xlib --with-x --x-includes="$XP/include" --x-libraries="$XP/lib" \
            --with-type-engines=xcore,xft --disable-dl-type --disable-dl-table --disable-dl-ctl \
