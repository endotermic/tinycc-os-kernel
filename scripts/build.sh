#!/bin/sh
# SPDX-License-Identifier: BSD-2-Clause
# build.sh - build the pinned, patched sources (src/) into a kernel + initramfs images
# (+ ISO) for one architecture.  Every step is skipped when its result exists.
#
# Usage: scripts/build.sh [--arch ARCH] [-n|--dry-run] [step...]        default: all
#   --arch ARCH   x86_64 (default) or i386, as ./build.sh and run.sh take it (arm64 is not
#                 implemented, see ./build.sh); the ARCH variable does the same
#   -n, --dry-run the clean steps print what would go and remove nothing (DRY_RUN=1 does the same)
#   -h, --help    this text
# Steps:
#   host-tcc    tinycc in src/tinycc (in-tree build; this compiler builds everything else)
#   tcc-test    run tinycc's own test suite (must print ALL TESTS PASSED)
#   tcc-archive install the host tcc into a staging tree and pack it as out/<arch>/tcc-*.tar.gz
#   tld         tools/tld (ld, nm, objcopy, readelf, ar, strip replacement) compiled by the host tcc
#   libelf      tools/libelf (the libelf subset the kernel's objtool needs) compiled by the host tcc
#   kernel      Linux: tinyconfig + kernels/linux/*.config, CC=tcc-kcc (kernels/linux/tcc-kcc.c), LD=tld
#   musl        musl libc, static, compiled by tcc (no src/complex: tcc has no _Complex), and
#               the musl-tcc driver wrapper
#   kernel-headers  the Linux UAPI headers (headers_install) the musl-tcc wrapper adds; busybox,
#               tinyx, ncurses, libressl, mlterm and links need them
#   busybox     static busybox compiled and linked by tcc against that musl
#   ncurses     ncurses, wide-char, static, musl, compiled by the host tcc, with the consoles'
#               terminfo entries compiled in (no terminfo files in the image): the library nnn needs
#   nnn         the nnn file manager, static, musl, against that ncurses -> /usr/bin/nnn in the images
#   libressl    LibreSSL's libcrypto, libssl and libtls, static, musl, compiled by the host tcc
#               without assembly (the TLS library for links) -> build/<arch>/libressl/install, and
#               its CA bundle as /etc/ssl/cert.pem in the images
#   zlib        zlib, static, musl, compiled by the host tcc -> build/<arch>/x/usr (the tree the
#               graphical mode's libraries share: one prefix, scripts/pkg-config.sh reads its .pc files)
#   libpng      libpng, static, musl, compiled by hand (no configure) -> build/<arch>/x/usr; links'
#               graphics mode requires it
#   xlibs       the X client stack for links' X driver: xorgproto, xtrans, libXau, xcb-proto, libxcb
#               (its C generated by the host's python3), libX11; static, musl -> build/<arch>/x/usr
#   xlib-NAME   one library of the X stack alone (NAME: one of the libraries the xlibs, tinyx,
#               xdm, jwm and xfiles steps build, e.g. xlib-libXt); the parallel graph runs these
#   tinyx       TinyX's Xfbdev (Tiny Core's kdrive X server, no XKB/xinput; userland/tinyx/Makefile,
#               no autotools), with libXdmcp (header), libfontenc, libXfont 1 (built-in fonts, no
#               FreeType) -> /usr/bin/Xfbdev and /usr/bin/startx (userland/startx.c) in the images
#   xdm         the graphical login: X.Org's xdm with its greeter linked in (patches/xdm), Xft text, after
#               libICE, libSM, libXext, libXt, libXmu, libXpm, libXaw and the Xft font stack (libXrender,
#               expat, FreeType, fontconfig, libXft: xft_stack, which the jwm step uses too); its configuration and C scripts
#               (userland/xdm/) and the helper text window xdm-help -> /usr/bin/xdm, /etc/X11/xdm in the images
#   jwm         the window manager: JWM with every optional library it can use (libXrender, Xinerama,
#               libXft fonts from FreeType + fontconfig + expat, libjpeg; libpng, libXpm, libXext,
#               libXmu from the steps above), static, musl; the DejaVu fonts, fontconfig's
#               configuration, fc-list/fc-match, the menu's icons and /etc/system.jwmrc
#               (userland/jwm/) in the images; startx and xdm's Xsession run it with links -g
#   mlterm      the terminal emulator of the graphical mode: mlterm, X11 with the Xft type engine on
#               the jwm step's font stack (DejaVu Sans Mono), its scrollbar and type engine linked in,
#               static, musl, with mlclient -> /usr/bin/mlterm, /usr/bin/mlclient, /etc/mlterm
#               (userland/mlterm/) in the images; JWM's menu and links' LINKS_XTERM run it
#   xfiles      the file manager of the graphical mode: xfiles (icon grid, drag and drop, thumbnails,
#               XEmbed) with libXfixes and libXcursor, the pop-up menu xmenu (patches/xmenu: no
#               Imlib2), the prompt dmenu, xprop and xrdb, all static, musl; the C scripts
#               xfilesctl, xfilesthumb and xdg-open, /etc/X11/Xresources, the Unifont fallback
#               font, and libpng/libjpeg/zlib with headers under /usr/lib, /usr/include for the
#               thumbnailer, libX11's locale data (userland/xfiles/) -> /usr/bin/xfiles ... in the images
#   xedit       the text editor of the graphical mode: X.Org's xedit on the Athena widgets (Xaw, Xmu,
#               Xt from the xdm step), static, musl, with its Lisp syntax-highlighting modes and
#               its app-defaults file -> /usr/bin/xedit, /usr/lib/X11/xedit/lisp in the images
#   wallpapers  the desktop background: the wallpaper program (userland/wallpaper/: draws a JPEG or
#               PNG on the root window, scaled to cover the screen without distortion, centred,
#               the overhang cut off; JWM's background command and xdm's Xsetup_0 run it), static,
#               musl, and the elementary OS photographs of src/wallpapers shrunk by it to just
#               cover WALLPAPER_SIZE (default 1920x1200) -> /usr/bin/wallpaper,
#               /usr/share/backgrounds/elementary/*.jpg, /usr/share/backgrounds/default.jpg
#               (Pablo Garcia Saldana) in the images
#   links       the links web browser, text mode and graphics mode (its X driver on that server:
#               startx; GIF, PNG and JPEG images), static, musl, with TLS from that LibreSSL (http:// and https://)
#               -> /usr/bin/links (+ links2) in the images
#   libnl       libnl-3 and libnl-genl-3 (netlink), static, musl -> build/<arch>/libnl/install
#   wifi        wpa_supplicant, wpa_cli, wpa_passphrase, hostapd, hostapd_cli and iw, static, musl,
#               on that libnl and LibreSSL (WPA2/WPA3, EAP), and the guest's wifi command
#               (userland/wifi/wifi.c) -> /usr/sbin, /usr/bin/wifi in the images
#   firmware    the firmware files the kernel's drivers request (Wi-Fi, Bluetooth, Realtek
#               Ethernet, regulatory.db), from linux-firmware -> out/<arch>/firmware.cpio.gz,
#               the ISO's second initrd (loaded into /lib/firmware)
#   guest-tcc   tcc itself (+ i386-tcc), static, musl, for the initramfs (/usr/bin/tcc in the guest)
#   guest-make  GNU make, static, musl, compiled by the host tcc (the guest's make for self-hosting)
#   initramfs   the libc-free init + the two cpio images (initramfs-nolibc.cpio, initramfs.cpio.gz) -> out/<arch>/
#   selfhost    the self-hosting image out/<arch>/initramfs-selfhost.cpio: the busybox image plus
#               the pruned kernel source, the tcc, tld and make sources, i386-tcc, tld, make, the
#               Kbuild wrappers, pre-generated Kconfig lexer/parser, and build-kernel /
#               build-toolchain / send-file (userland/selfhost/); needs a complete kernel build
#   iso         hybrid BIOS/UEFI GRUB ISO -> out/<arch>/ (boot/mkiso.sh; with the self-hosting
#               image's menu entries when it exists)
#   all         host-tcc tld libelf kernel musl kernel-headers busybox ncurses nnn libressl zlib libpng xlibs tinyx xdm jwm mlterm xfiles xedit wallpapers links libnl wifi firmware guest-tcc initramfs
#   clean       remove build/<arch>/ and out/<arch>/ (the build trees, logs and results of ARCH);
#               src/ stays, and with it the host tcc, which is built in-tree in src/tinycc
#   clean-all   everything a build made or fetched: build/ and out/ as a whole (every
#               architecture), the fetched sources (src/<name>, src/.downloads; with the same
#               check as clean-src, made before anything is removed) and the binaries a make in
#               tools/tld leaves there
#   clean-src   remove the fetched component trees src/<name> and src/.downloads (scripts/fetch.sh +
#               scripts/patch.sh recreate them: a 2 GB download); refuses while a tree has
#               uncommitted changes, a stash, or more commits on top of 'base' than
#               patches/<name>/series lists (fixes are committed there and exported with
#               scripts/export-patches.sh before the tree may go)
# Every clean step prints what goes with its size (du -sh).  The whole command line is checked
# before the first step runs: an unknown step or option aborts with nothing done.  Every step
# first checks that the host has what it needs and names the missing packages.
# Env: ARCH, JOBS (parallel jobs; default nproc), SRC/BUILD/OUT (the directories, see
#   scripts/lib.sh), DRY_RUN, WALLPAPER_SIZE (the wallpapers step: WIDTHxHEIGHT the
#   photographs are shrunk to cover; default 1920x1200).
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd)
. "$ROOT/scripts/lib.sh"
# --arch first: everything below depends on the architecture; the other arguments are checked
# at the end, before the first step runs
n=$#
while [ $n -gt 0 ]; do
    n=$((n - 1))
    case $1 in
        --arch) [ $# -gt 1 ] || die "--arch needs an architecture (x86_64, i386)"; ARCH=$2; shift 2; n=$((n - 1));;
        --arch=*) ARCH=${1#--arch=}; shift;;
        *) set -- "$@" "$1"; shift;;
    esac
done
ARCH=${ARCH:-x86_64}
JOBS=${JOBS:-$(nproc)}
# KARCH: the kernel's ARCH= (i386 selects the 32-bit kernel); TCC_TARGET: the compiler of the
# target code (the i386 cross compiler built next to the host tcc for i386: "tcc -m32" would
# exec it anyway); LIBTCC1: its runtime archive, for the musl-tcc wrapper; TCC_CPU: tcc's
# configure --cpu for the guest compiler; the self-hosting image of the i386 guest needs no
# i386 cross compiler (tcc there is the i386 compiler, -m16 is native)
case $ARCH in
    x86_64) KARCH=x86;   KIMG=arch/x86/boot/bzImage; TCC_TARGET=tcc;      LIBTCC1=libtcc1.a;      TCC_CPU=x86_64; CROSS_I386=1;;
    i386)   KARCH=i386;  KIMG=arch/x86/boot/bzImage; TCC_TARGET=i386-tcc; LIBTCC1=i386-libtcc1.a; TCC_CPU=i386;   CROSS_I386=;;
    *) die "--arch $ARCH is not implemented (x86_64, i386; see ./build.sh --help)";;
esac
B=$BUILD/$ARCH; LOGS=$B/logs; O=$OUT/$ARCH
# the source copies under build/ must not see this repository's own .git (tcc's and
# busybox's version strings ask git about the tree they are built from)
export GIT_CEILING_DIRECTORIES=$BUILD
# progress-bar totals for the two builds whose step count "make -n" cannot tell; corrected
# from the real count after the first complete build (build/<arch>/steps/<name>)
KERNEL_STEPS_DEFAULT=1190
BUSYBOX_STEPS_DEFAULT=660
STEPS=$B/steps
# the build steps' directories (made right before a build step runs, so that the clean steps
# leave nothing behind)
prepare() { mkdir -p "$B" "$LOGS" "$O" "$STEPS"; }
TCCSRC=$SRC/tinycc; TCC=$TCCSRC/tcc; TCC_TARGET=$TCCSRC/$TCC_TARGET; LIBTCC1=$TCCSRC/$LIBTCC1
LINUX=$SRC/linux; MUSLSRC=$SRC/musl; BBSRC=$SRC/busybox; NCSRC=$SRC/ncurses; NNNSRC=$SRC/nnn; FTSSRC=$SRC/musl-fts
LINKSSRC=$SRC/links; LSSLSRC=$SRC/libressl
# the graphical mode: zlib, libpng, the X headers and client libraries, libXfont and TinyX
# are built into one tree, $XP (--prefix), so that one -I and one -L reach all of them;
# their configure scripts run with scripts/pkg-config.sh, which reads $XP's .pc files only
XB=$B/x; XP=$XB/usr; TINYXSRC=$SRC/tinyx; ZSRC=$SRC/zlib; PNGSRC=$SRC/libpng
x_env() {
    export PKG_CONFIG=$ROOT/scripts/pkg-config.sh PKG_CONFIG_LIBDIR=$XP/lib/pkgconfig:$XP/share/pkgconfig
    unset PKG_CONFIG_PATH PKG_CONFIG_SYSROOT_DIR
}
# the terminals a guest console can be (TERM is set by /init, userland/busybox-init.c): their
# terminfo entries are compiled into libncursesw (step_ncurses), so the image carries none
NCURSES_FALLBACKS=linux,vt100,vt102,vt220,xterm,xterm-256color,screen,screen-256color,tmux,tmux-256color,ansi,dumb
MUSLB=$B/musl; MUSLP=$MUSLB/install; KHDR=$B/kernel-headers; MUSL_TCC=$B/musl-tcc

need_src() {
    for n; do
        [ -d "$SRC/$n/.git" ] || die "src/$n is missing: run scripts/fetch.sh"
        if [ -f "$ROOT/patches/$n/series" ]; then
            [ "$(git -C "$SRC/$n" rev-parse --abbrev-ref HEAD)" = patched ] \
                || die "src/$n is not on the 'patched' branch: run scripts/patch.sh"
        fi
    done
}
fail() { tail -n 25 "$1" >&2; die "$2 (log: $1)"; }
# configured FILE STRING...: FILE (a configure output) exists and records every STRING.  The
# configure scripts write absolute paths (CC, srcdir, prefix) into config.mak / config.status;
# when the repository or its build tree has moved, those files exist but point to nowhere, so
# the steps re-run configure instead of trusting that the file is there.
configured() {
    f=$1; shift
    [ -f "$f" ] || return 1
    for sv; do grep -qF -- "$sv" "$f" && continue
        echo "   $f was configured for another path: re-running configure"
        rm -f "$f"; return 1
    done
}
# jrun CMD...: CMD (a make, or env ... make) with the build's parallelism.  A step run alone
# gets -j$JOBS; a step of the parallel graph (scripts/parallel.sh) gets the graph's one make
# jobserver instead (JOBSERVER_FLAGS: "-jN --jobserver-auth=fifo:PATH", from the job wrapper),
# so that every step's compilers together stay within the graph's N jobs.  jmake ARGS: jrun make.
# (The other make calls, the installs, run with MAKEFLAGS unset: one job, as before.)
jrun() {
    if [ -n "${JOBSERVER_FLAGS:-}" ]; then MAKEFLAGS=$JOBSERVER_FLAGS "$@"
    else "$@" -j"$JOBS"; fi
}
jmake() { jrun make "$@"; }
# "<upstream commit>+<n> patches", e.g. "e23dabe+53p": tcc's version suffix (see step_host_tcc)
tcc_tag() { echo "$(git -C "$TCCSRC" rev-parse --short base)+$(git -C "$TCCSRC" rev-list --count base..HEAD)p"; }

step_host_tcc() {
    need_src tinycc
    msg "host tcc: src/tinycc (in-tree, $(git -C "$TCCSRC" rev-list --count base..HEAD) patches on $(git -C "$TCCSRC" rev-parse --short base))"
    cd "$TCCSRC"
    [ -f config.mak ] || ./configure >"$LOGS/tcc-configure.log" 2>&1 || fail "$LOGS/tcc-configure.log" "tcc configure failed"
    # a stable version string: Kbuild rebuilds everything when CC's version text changes,
    # and every re-application of the series gives the commits new hashes.  The string is a
    # -D define, which make does not track: recompile the object that embeds it when the
    # patch count changed since the last build
    if [ "$(cat "$B/tcc-tag" 2>/dev/null)" != "$(tcc_tag)" ]; then
        rm -f "$TCCSRC"/libtcc.o "$TCCSRC"/tcc.o "$TCCSRC"/i386-libtcc.o "$TCCSRC"/i386-tcc.o
        echo "$(tcc_tag)" > "$B/tcc-tag"
    fi
    : >"$LOGS/tcc-build.log"
    run_progress "tcc" "$(make_total GITHASH="$(tcc_tag)" GITMODF=)" "$LOGS/tcc-build.log" \
        jmake GITHASH="$(tcc_tag)" GITMODF= || fail "$LOGS/tcc-build.log" "tcc build failed"
    # the i386 cross compiler: tcc -m16/-m32 exec it for the kernel's real-mode code
    jmake cross-i386 GITHASH="$(tcc_tag)" GITMODF= >>"$LOGS/tcc-build.log" 2>&1 || fail "$LOGS/tcc-build.log" "i386-tcc build failed"
    echo "   $("$TCC" -v), $("$TCCSRC/i386-tcc" -v)"
}

step_tcc_test() {
    need_src tinycc
    msg "tcc test suite"
    : >"$LOGS/tcc-test.log"
    PROGRESS_STEP_RE='.'
    run_progress "tcc tests" 0 "$LOGS/tcc-test.log" make -C "$TCCSRC" -s test -k || true
    unset PROGRESS_STEP_RE
    grep -q 'ALL TESTS PASSED' "$LOGS/tcc-test.log" || fail "$LOGS/tcc-test.log" "tcc tests did not all pass"
    echo "   ALL TESTS PASSED"
}

step_tcc_archive() {
    need_src tinycc
    [ -x "$TCC" ] || die "no host tcc: run the host-tcc step first"
    D=$B/tcc-dist
    msg "tcc archive: make install into $D, packed into $O"
    rm -rf "$D"
    (cd "$TCCSRC" && make -s install DESTDIR="$D" GITHASH="$(tcc_tag)" GITMODF=) >"$LOGS/tcc-install.log" 2>&1 \
        || fail "$LOGS/tcc-install.log" "tcc install failed"
    prefix=$(sed -n 's/^prefix=//p' "$TCCSRC/config.mak" | head -1); prefix=${prefix:-/usr/local}
    doc=$D$prefix/share/doc/tinycc-os-kernel; mkdir -p "$doc"
    { echo "Tiny C Compiler $("$TCC" -v | awk '{print $3}') from tinycc-os-kernel"
      echo "upstream: $(lock_urls tinycc | awk '{print $1}') commit $(git -C "$TCCSRC" rev-parse base)"
      echo "plus these $(git -C "$TCCSRC" rev-list --count base..HEAD) patches (patches/tinycc/ in the repository):"
      git -C "$TCCSRC" log --reverse --format='  %s' base..HEAD
    } > "$doc/PATCHES"
    ar=$O/tcc-$("$TCC" -v | awk '{print $3}')-$(tcc_tag)-$ARCH-linux.tar.gz
    tar czf "$ar" -C "$D" .
    echo "   $(ls -l "$ar" | awk '{print $5}') bytes: $ar"
    echo "   contents: $(find "$D" -type f | wc -l) files under $prefix (bin/tcc, lib/tcc/, include/libtcc.h, share/doc)"
}

step_tld() {
    [ -x "$TCC" ] || die "no host tcc: run the host-tcc step first"
    TLD=$B/tld; mkdir -p "$TLD"
    msg "tld: tools/tld (ld, nm, objcopy, readelf, ar, strip) compiled by the host tcc -> $TLD"
    "$TCC" -B"$TCCSRC" -I"$TCCSRC/include" -std=gnu99 -O2 -o "$TLD/tld" "$ROOT"/tools/tld/*.c \
        || die "tld build failed"
    for t in ld nm objcopy readelf ar strip; do ln -sf tld "$TLD/$t"; done
    echo "   $("$TLD/ld" -v), $(ls -l "$TLD/tld" | awk '{print $5}') bytes"
}

# the libelf subset the kernel's objtool needs (tools/libelf): headers, libelf.a and a
# pkg-config stand-in that answers for it, so that Kbuild builds the real objtool with
# HOSTCC=tcc-hostcc and no host libelf
step_libelf() {
    [ -x "$TCC" ] || die "no host tcc: run the host-tcc step first"
    LIBELF=$B/libelf
    msg "libelf: tools/libelf (the libelf subset objtool needs) compiled by the host tcc -> $LIBELF"
    rm -rf "$LIBELF"
    make -s -C "$ROOT/tools/libelf" CC="$TCC -B$TCCSRC -I$TCCSRC/include" AR="$TCC -ar" PREFIX="$LIBELF" \
        || die "libelf build failed"
    echo "   libelf.a $(ls -l "$LIBELF/lib/libelf.a" | awk '{print $5}') bytes; pkg-config: $("$LIBELF/pkg-config" libelf --cflags --libs)"
}

step_kernel() {
    need_src linux
    [ -x "$TCC" ] || die "no host tcc: run the host-tcc step first"
    [ -x "$TCCSRC/i386-tcc" ] || die "no $TCCSRC/i386-tcc (the host-tcc step builds it): the real-mode code needs tcc -m16"
    KFRAGS="minimal.config drivers.config $ARCH.config tcc.config"
    TLD=$B/tld; [ -x "$TLD/ld" ] || die "no $TLD/ld: run the tld step first"
    LIBELF=$B/libelf; [ -x "$LIBELF/pkg-config" ] || die "no $LIBELF/pkg-config: run the libelf step first"
    KB=$B/linux; mkdir -p "$KB"
    msg "kernel: ARCH=$KARCH tinyconfig + kernels/linux/{minimal,drivers,$ARCH,tcc}.config, CC=tcc-kcc ($TCC_TARGET) -> $KB"
    # the Kbuild wrappers are C programs (kernels/linux/*.c; the guest runs the same sources
    # as tcc -run scripts): compiled here by the host tcc for this build
    KCC=$B/kcc; mkdir -p "$KCC"
    for w in tcc-kcc tcc-hostcc; do
        "$TCC" -B"$TCCSRC" -I"$TCCSRC/include" -O2 -o "$KCC/$w" "$ROOT/kernels/linux/$w.c" || die "$w build failed"
    done
    KCC_LOG=$LOGS/kcc.log
    : >"$KCC_LOG"
    # TCC and KCC_LOG are given to this make only (not exported: GNU make re-exports a
    # variable that came from the environment with its own value, which would break the
    # musl-tcc wrapper during the tcc builds)
    # HOSTCC: the host tools (fixdep, kconfig, modpost, sorttable, relocs, vdso2c, objtool, ...)
    # are compiled by tcc too; objtool links against tools/libelf (HOSTPKG_CONFIG, the
    # stand-in of the libelf step, says where it is) and tools/build merges its objects with
    # HOSTLD -r and HOSTAR, which are tld's
    # the binutils are tld's: LD/NM/OBJCOPY/READELF/AR/STRIP (no objdump is needed)
    # KBUILD_BUILD_VERSION=1: the build number counts the generations (uname -v "#1"); a kernel
    # built inside the guest by userland/selfhost/build-kernel is #2, and so on
    # KCC_TCC: the compiler tcc-kcc runs for the target code (TCC stays the host compiler for
    # tcc-hostcc); for i386 the cross compiler next to it
    # KCFLAGS: kernels/linux/tcc-canary.h defines the seqlock canary __scoped_seqlock_bug() as
    # the empty stub the kernel uses for GCC 8 (tcc cannot prove the call dead), so the tree
    # needs no patch for it; build-kernel passes the same flag in the guest
    MK="env TCC=$TCC KCC_TCC=$TCC_TARGET KCC_LOG=$KCC_LOG make -C $LINUX O=$KB ARCH=$KARCH CC=$KCC/tcc-kcc HOSTCC=$KCC/tcc-hostcc HOSTPKG_CONFIG=$LIBELF/pkg-config HOSTLD=$TLD/ld HOSTAR=$TLD/ar LD=$TLD/ld NM=$TLD/nm OBJCOPY=$TLD/objcopy READELF=$TLD/readelf AR=$TLD/ar STRIP=$TLD/strip KBUILD_BUILD_VERSION=1 KCFLAGS=-include$ROOT/kernels/linux/tcc-canary.h"
    if [ ! -f "$KB/.config" ]; then
        $MK -s tinyconfig >"$LOGS/kernel-config.log" 2>&1 || fail "$LOGS/kernel-config.log" "tinyconfig failed"
    fi
    # the fragments are merged on every run, so that a line added to them reaches an existing
    # build tree too (olddefconfig then resolves the dependencies; Kbuild rebuilds what changed)
    for f in $KFRAGS; do
        "$LINUX/scripts/kconfig/merge_config.sh" -m -O "$KB" "$KB/.config" "$ROOT/kernels/linux/$f" >>"$LOGS/kernel-config.log" 2>&1
    done
    $MK -s olddefconfig >>"$LOGS/kernel-config.log" 2>&1 || fail "$LOGS/kernel-config.log" "olddefconfig failed"
    # every fragment line must survive olddefconfig, unless a later fragment sets the same
    # option (i386.config leaves out drivers.config's amdgpu and xe)
    for f in $KFRAGS; do
        later=$(echo "$KFRAGS" | sed "s/.*$f//")
        grep -E '^(CONFIG_|# CONFIG_.* is not set)' "$ROOT/kernels/linux/$f" | while IFS= read -r line; do
            grep -qxF -- "$line" "$KB/.config" && continue
            opt=$(echo "$line" | sed -E 's/^# //; s/[= ].*//')
            for g in $later; do grep -qE "^(# )?$opt[= ]" "$ROOT/kernels/linux/$g" && continue 2; done
            case $line in
                "# CONFIG_"*" is not set")   # absent altogether = not available for this compiler
                    opt=${line#\# }; opt=${opt%% *}
                    grep -q "^$opt=" "$KB/.config" || continue;;
            esac
            echo "   NOT APPLIED ($f): $line"
        done
    done
    total=$(cat "$STEPS/kernel" 2>/dev/null || echo "$KERNEL_STEPS_DEFAULT")
    learn=1; [ ! -f "$KB/vmlinux" ] || learn=0   # only a complete build teaches the total
    : >"$LOGS/kernel.log"
    PROGRESS_COUNT_FILE=$STEPS/kernel.new
    run_progress "kernel" "$total" "$LOGS/kernel.log" jrun $MK \
        || { grep -E ' error: |Error [0-9]|undefined reference' "$LOGS/kernel.log" | head -20 >&2; fail "$LOGS/kernel.log" "kernel build failed"; }
    unset PROGRESS_COUNT_FILE
    [ $learn = 0 ] || [ "$(cat "$STEPS/kernel.new")" = 0 ] || mv "$STEPS/kernel.new" "$STEPS/kernel"
    cp "$KB/$KIMG" "$O/bzImage"
    echo "   $(grep -c '^tcc ' "$KCC_LOG") tcc and $(grep -c '^gcc ' "$KCC_LOG") gcc compiler invocations; $(ls -l "$O/bzImage" | awk '{print $5}') bytes bzImage"
}

# the Linux UAPI headers for musl-tcc (-isystem $KHDR/include): musl ships none.  busybox,
# TinyX (<linux/fb.h>), ncurses, LibreSSL and mlterm include them, links' configure probes
