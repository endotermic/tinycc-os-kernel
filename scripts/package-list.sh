#!/bin/sh
# SPDX-License-Identifier: BSD-2-Clause
# package-list.sh - print the release's package list as a Markdown table: every component of
# sources.lock with its version, where its source comes from (a release tarball or a git
# commit) and how many patches of patches/<component>/series it carries.  The release notes,
# the website's download page and DistroWatch's package table are made from it.
# Usage: scripts/package-list.sh [--text]     (--text: "name version" lines only)
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd)
. "$ROOT/scripts/lib.sh"
case ${1:-} in -h|--help) usage;; esac
text=; [ "${1:-}" = --text ] && text=1

# the release, from the image's /etc/os-release
rel=$(sed -n 's/^PRETTY_NAME="\(.*\)"/\1/p' "$ROOT/userland/etc/os-release")

version() {    # $1 component: the version a reader knows it by
    v=$(lock_ref "$1"); c=$(lock_commit "$1")
    case $1 in
    linux)  # a master snapshot: the kernel's own version, from its Makefile when fetched
        mk=$SRC/linux/Makefile
        if [ -f "$mk" ]; then
            v=$(awk '$1=="VERSION"{a=$3} $1=="PATCHLEVEL"{b=$3} $1=="SUBLEVEL"{c=$3} END{print a"."b"."c"+"}' "$mk")
        fi;;
    tinycc) # the mob branch: the version tcc reports, from its VERSION file when fetched
        [ ! -f "$SRC/tinycc/VERSION" ] || v=$(cat "$SRC/tinycc/VERSION");;
    esac
    # tags as release numbers: v1.2.6 -> 1.2.6, 1_38_0 -> 1.38.0
    case $v in v[0-9]*) v=${v#v};; esac
    case $v in [0-9]*_*) v=$(printf %s "$v" | tr _ .);; esac
    case $c in
    sha256:*) ;;
    *) case $v in master|main|mob|[0-9]*+) v="$v (git $(printf %.8s "$c"))";; esac;;
    esac
    printf '%s' "$v"
}

if [ -n "$text" ]; then
    for n in $(lock_names); do printf '%s %s\n' "$n" "$(version "$n" | tr ' ' '_')"; done
    exit 0
fi

printf '# Packages of %s\n\n' "$rel"
printf 'Every component is built from source by the patched Tiny C Compiler (tcc), with no GCC\n'
printf 'and no binutils, except the data: the fonts, the firmware (linux-firmware, sof-bin, wireless-regdb)\n'
printf 'and the wallpapers.\n'
printf 'Generated by `scripts/package-list.sh` from `sources.lock`.\n\n'
printf '| Package | Version | Source | Patches |\n|---|---|---|---|\n'
for n in $(lock_names); do
    case $(lock_commit "$n") in sha256:*) src="release tarball";; *) src="git";; esac
    s=$ROOT/patches/$n/series
    p=0; [ ! -f "$s" ] || p=$(series_files "$s" | wc -l | tr -d ' ')
    printf '| %s | %s | %s | %s |\n' "$n" "$(version "$n")" "$src" "$p"
done
